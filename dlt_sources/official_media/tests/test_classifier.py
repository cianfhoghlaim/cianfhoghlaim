def test_returns_none_when_baml_raises(monkeypatch: pytest.MonkeyPatch) -> None:
    """If BAML raises (LiteLLM gateway down, schema parse error,
    rate limit, etc.) the wrapper returns ``None`` and never raises."""
    mock_baml = MagicMock()
    mock_baml.ClassifyOfficialMedia.side_effect = RuntimeError("LiteLLM down")
    monkeypatch.setattr(classifier_module, "_baml_client", mock_baml)

    result = classify_with_baml("test_handle")
    assert result is None


