def test_allowlist_filter_invokes_baml_fallback() -> None:
    """End-to-end: AllowlistFilter with the BAML classifier wired in
    accepts a candidate that looks official (heuristic match) when
    BAML returns is_official_media=True with high confidence."""
    from dlt_sources.official_media.allowlist import AllowlistFilter

    def fake_baml(ig_username: str, ig_bio: str, ig_external_url: str) -> dict:
        return {
            "is_official_media": True,
            "confidence": 0.9,
            "category": "jurisdiction",
            "reason": f"{ig_username} is the official police account",
        }

    filt = AllowlistFilter(baml_classifier=fake_baml, confidence_threshold=0.7)
    match = filt.classify(
        "met_police_official_2024",
        bio="The official Metropolitan Police account",
        external_url="https://www.met.police.uk",
    )
    assert match.is_official is True
    assert match.stage == 2
    assert match.category == "jurisdiction"
    assert match.source == "baml_classifier"
