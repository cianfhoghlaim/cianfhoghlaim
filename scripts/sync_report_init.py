#!/usr/bin/env python3
"""Helper: regenerate the sync-report directory + create the per-layer templates.

Per the 2026-08-15-knowledge-sync-loop-v1 change.
Run on first sync to bootstrap the stedding/sync-reports/ directory.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPORT_DIR = Path("stedding/sync-reports")


def main() -> int:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    # Add a .gitkeep so the dir is tracked (we don't want the actual
    # sync reports tracked since they change daily)
    gitkeep = REPORT_DIR / ".gitkeep"
    if not gitkeep.exists():
        gitkeep.write_text(
            "# Per-layer sync reports (auto-generated by 'mise run sync:all')\n"
            "# These files are NOT tracked in git; they're regenerated on\n"
            "# every sync run. See .gitignore at the repo root.\n"
        )
    print(f"OK: {REPORT_DIR} ready")
    return 0


if __name__ == "__main__":
    sys.exit(main())
