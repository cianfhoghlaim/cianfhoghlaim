/**
 * Convert a snake_case subject slug to a camelCase identifier.
 * E.g. "computer_science" → "computerScience".
 */
export function toIdentifier(slug: string): string {
  return slug.replace(/_(\w)/g, (_, c: string) => c.toUpperCase());
}

/**
 * Convert a snake_case subject slug to a PascalCase type name.
 * E.g. "computer_science" → "ComputerScience".
 */
export function pascalCase(slug: string): string {
  const id = toIdentifier(slug);
  return id.charAt(0).toUpperCase() + id.slice(1);
}

