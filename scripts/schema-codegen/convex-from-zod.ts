/**
 * scripts/schema-codegen/convex-from-zod.ts
 *
 * Step 2 of the schema-driven codegen pipeline (per the
 * 2026-08-13-web-monorepo-consolidation-and-agent-integration-v1
 * change, Phase O).
 *
 * Emits Convex table definitions + validators from the BAML/Zod schemas
 * emitted by step 1 (`baml-to-ts.ts`).
 *
 * For each (stage, subject) pair, this step writes:
 *   - web/apps/oideachais-dashboard/convex/<stage>/<subject>.ts
 *     — the per-subject Convex table schema (defineTable + defineSchema)
 *   - web/apps/oideachais-dashboard/convex/<stage>/<subject>.types.ts
 *     — the per-subject type re-exports
 *
 * The Convex table schema uses `app: v.literal('<app>')` + `subject: v.literal('<subject>')`
 * to filter per the `app + subject` field convention from the
 * web-monorepo-consolidation spec.
 *
 * Returns: array of emitted file paths (relative to repo root).
 */

import * as path from "node:path";
import * as fs from "node:fs/promises";

import type { SubjectRow } from "./index";

// =============================================================================
// Public API
// =============================================================================

export async function runConvexFromZod(
  repoRoot: string,
  subjects: ReadonlyArray<SubjectRow>,
  dryRun: boolean,
): Promise<ReadonlyArray<string>> {
  console.log(`\n[2/5] convex-from-zod (${subjects.length} subjects)`);

  const emitted: string[] = [];
  const convexDir = path.join(
    repoRoot,
    "web/apps/oideachais-dashboard/convex",
  );

  for (const row of subjects) {
    const perStage = `${row.stage}/${row.subject}`;
    const perPath = path.join(convexDir, row.stage, `${row.subject}.ts`);
    const typesPath = path.join(
      convexDir,
      row.stage,
      `${row.subject}.types.ts`,
    );

    const schemaSource = renderConvexSchema(row);
    const typesSource = renderConvexTypes(row);

    if (!dryRun) {
      await fs.mkdir(path.dirname(perPath), { recursive: true });
      await fs.writeFile(perPath, schemaSource);
      await fs.writeFile(typesPath, typesSource);
    }

    emitted.push(
      `web/apps/oideachais-dashboard/convex/${perStage}.ts`,
      `web/apps/oideachais-dashboard/convex/${row.stage}/${row.subject}.types.ts`,
    );
  }

  // Update the umbrella schema to reference the new per-subject tables.
  if (!dryRun) {
    await updateUmbrellaSchema(repoRoot, subjects);
  }

  console.log(`  emitted ${emitted.length} files`);
  return emitted;
}

