/**
 * Render the per-subject Convex schema file. Uses `defineTable` +
 * `defineSchema` per the Convex v0.19+ canonical pattern.
 */
export function renderConvexSchema(row: SubjectRow): string {
  const identifier = toIdentifier(row.subject);
  const tableName = `${row.stage}_${row.subject}`;
  const commentLines = [
    ` * Per-subject Convex table for ${row.stage.toUpperCase()} ${row.display_name}.`,
    ` *`,
    ` * AUTO-GENERATED by scripts/schema-codegen/convex-from-zod.ts (Phase O).`,
    ` * DO NOT EDIT — re-run \`bun run scripts/schema-codegen/index.ts\` to update.`,
    ` *`,
    ` * Reference:`,
    ` *   openspec/changes/2026-08-13-web-monorepo-consolidation-and-agent-integration-v1/`,
    ` *   specs/schema-driven-codegen/spec.md`,
    ``,
    ` * Subject metadata:`,
    ` *   stage:     ${row.stage}`,
    ` *   subject:   ${row.subject}`,
    ` *   ncca_code: ${row.ncca_code}`,
    ` *   languages: ${row.languages.join(", ")}`,
  ];

  return `/**
${commentLines.join("\n")}
 */

import { defineTable, v, defineSchema } from "convex/schema";
import { ${identifier}Type } from "./${row.subject}.types";

export const ${identifier} = defineTable({
  app: v.literal("oideachais"),
  stage: v.literal("${row.stage}"),
  subject: v.literal("${row.subject}"),
  language: v.union(
${row.languages.map((l) => `    v.literal("${l}")`).join(",\n")},
  ),
  // Per-subject BAML-extracted fields:
  syllabus_topic_code: v.string(),
  syllabus_topic_title: v.string(),
  learning_outcome_code: v.string(),
  learning_outcome_text: v.string(),
  blooms_level: v.union(
    v.literal("remember"),
    v.literal("understand"),
    v.literal("apply"),
    v.literal("analyse"),
    v.literal("evaluate"),
    v.literal("create"),
  ),
  // BAML ${identifier}Payload fields (the structured extraction output):
  payload: v.object(${identifier}Type),
  // Metadata:
  ncca_code: v.string(),
  created_at: v.number(),  // epoch ms
  updated_at: v.number(),
})
  .index("by_app_stage_subject", ["app", "stage", "subject"])
  .index("by_topic", ["syllabus_topic_code"])
  .index("by_ncca_code", ["ncca_code"]);

// Re-export the type for the umbrella schema
export type ${identifier}Doc = typeof ${identifier}DocSchema;
declare const ${identifier}DocSchema: never;
`;
}

/**
 * Render the per-subject Convex types file. References the BAML-generated
 * types from step 1.
 */
export function renderConvexTypes(row: SubjectRow): string {
  const identifier = toIdentifier(row.subject);
  const typeName = pascalCase(row.subject);

  return `/**
 * Per-subject Convex types for ${row.stage.toUpperCase()} ${row.display_name}.
 *
 * AUTO-GENERATED by scripts/schema-codegen/convex-from-zod.ts (Phase O).
 * DO NOT EDIT — re-run \`bun run scripts/schema-codegen/index.ts\` to update.
 *
 * Re-exports the BAML-generated ${typeName}* types from step 1 + adds the
 * Convex-specific doc type.
 */

import type { Doc as BaseDoc } from "convex/server";

import type {
  ${typeName}Syllabus,
  ${typeName}Paper,
  ${typeName}MarkingScheme,
  ${typeName}Topics,
} from "../../../../baml_client/typescript/baml_client/${row.stage}/${row.subject}/client";

/**
 * The BAML-generated ${typeName}Payload type (the union of the 4 extraction
 * functions' outputs).
 */
export type ${typeName}Payload =
  | ${typeName}Syllabus
  | ${typeName}Paper
  | ${typeName}MarkingScheme
  | ${typeName}Topics;

/**
 * The per-subject Convex doc type (the BAML payload + Convex metadata).
 */
export interface ${typeName}Doc extends BaseDoc {
  app: "oideachais";
  stage: "${row.stage}";
  subject: "${row.subject}";
  language: ${row.languages.map((l) => `"${l}"`).join(" | ")};
  syllabus_topic_code: string;
  syllabus_topic_title: string;
  learning_outcome_code: string;
  learning_outcome_text: string;
  blooms_level:
    | "remember"
    | "understand"
    | "apply"
    | "analyse"
    | "evaluate"
    | "create";
  payload: ${typeName}Payload;
  ncca_code: string;
  created_at: number;
  updated_at: number;
}

// Re-export the BAML ${identifier}Type alias for the schema file
export type ${identifier}Type = ${typeName}Payload;
`;
}

