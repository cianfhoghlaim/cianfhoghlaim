"""The Cianfhoghlaim Educational MMO — per-subject progress dashboard.

Per R7.9: the MMO end-to-end demo, covering the 8 NCCA Leaving
Certificate subjects (mathematics, applied_mathematics, chemistry,
geography, history, english, gaeilge, computer_science).

For each subject, the dashboard reads the live BGE-M3 quest-pack counts
from the MotherDuck + DuckLake lakehouse (``md:oideachais``) and surfaces:

1. **Syllabus coverage** — % of the canonical subject topics that have
   been embedded into LanceDB.
2. **Quest-pack inventory** — counts of formative items generated by
   the v4 BAML quest-pack functions (``Generate<Subject>QuestPack``).
3. **Per-realm Badges** — SkilTreeBadge rows per subject
   (``oideachais.mmo.skill_tree_badges``).
4. **Daily Merkle anchor status** — the on-chain credential anchor that
   fires at 23:50 UTC (``oideachais.mmo.daily_anchors``).

Falls back to a deterministic synthetic summary when the lakehouse is
unreachable so the dashboard still renders during local dev.
"""
